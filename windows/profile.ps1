# f: fuzzy open. Pick a file (bat-previewed), open it in micro.
function f {
    $file = fzf --preview 'bat --color=always --line-range=:200 {}'
    if ($file) { & $env:EDITOR $file }
}

# rgf: live content search. Type a regex, results refresh each keystroke,
# Enter opens the match in micro.
function rgf {
    param([string]$Query = '')
    $rg = 'rg --line-number --no-heading --color=always --smart-case'
    # fzf runs reload commands through cmd.exe on Windows, which has no `|| true`;
    # `|| cd .` is the no-op equivalent that keeps a zero-match rg from erroring.
    # Unlike zsh's one-shot `VAR=x cmd` prefix, $env: assignment persists — restore it.
    $prev = $env:FZF_DEFAULT_COMMAND
    $env:FZF_DEFAULT_COMMAND = "$rg -- ""$Query"""
    try {
        $out = fzf --ansi --disabled --query $Query `
                   --bind "change:reload:$rg -- {q} || cd ." `
                   --delimiter : `
                   --preview 'bat --color=always --highlight-line {2} {1}' `
                   --preview-window 'up,60%,+{2}/3'
    } finally {
        $env:FZF_DEFAULT_COMMAND = $prev
    }
    if (-not $out) { return }
    $parts = $out -split ':', 3
    micro "+$($parts[1])" $parts[0]
}

