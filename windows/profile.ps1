# fnm/zoxide/oh-my-posh init scripts are static per tool-version/theme but each
# normally gets regenerated by spawning its binary on every single new shell.
# Cache the generated script once instead; rerun this manually after changing
# fnm/zoxide/oh-my-posh versions or theme.
function rebuildShellCache {
    $cacheDir  = "$HOME\.cache\pwsh"
    $cacheFile = "$cacheDir\init-cache.ps1"
    New-Item -ItemType Directory -Path $cacheDir -Force | Out-Null
    $fnmInit    = if (Get-Command fnm -ErrorAction SilentlyContinue) { fnm env --use-on-cd --shell power-shell | Out-String } else { '' }
    $zoxideInit = zoxide init powershell | Out-String
    $ompInit    = oh-my-posh init pwsh --config "$HOME\.config\oh-my-posh\powerlevel10k_classic.omp.json" | Out-String
    @"
# Auto-generated by rebuildShellCache (see `$PROFILE) — do not hand-edit.
$fnmInit
$zoxideInit
$ompInit
"@ | Set-Content -Path $cacheFile -Encoding utf8
    Write-Host "Shell init cache rebuilt at $cacheFile"
}
